const NOW = new Date('2026-11-10T08:00:00.000Z');

const NEVER_EDIT =
  'A stored draft of an earlier version must stay readable: phones keep drafts across releases. ' +
  'Raise DRAFT_RECORD_VERSION in draft-store.ts, add an upgrade reader for the earlier records ' +
  'and golden records of the new version. Never edit or delete an existing golden record.';

/** Runs `check` and names the rule when it fails. */
async function pinned(check: () => Promise<void> | void, rule: string): Promise<void> {
  try {
    await check();
  } catch (failure) {
    throw new Error(`${rule}\n\n${failure instanceof Error ? failure.message : String(failure)}`);
  }
}

/** A golden record as IndexedDB holds it: every `$blob` becomes a Blob again. */
function revived(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(revived);
  if (!isJsonRecord(value)) return value;
  const blob = value.$blob;
  if (isJsonRecord(blob) && typeof blob.type === 'string' && typeof blob.text === 'string')
    return new Blob([blob.text], { type: blob.type });
  return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, revived(entry)]));
}

/** A golden record as IndexedDB holds it, to change one field of. */
function revivedRecord(value: unknown): Record<string, unknown> {
  const record = revived(value);
  if (!isJsonRecord(record)) throw new Error('A golden record is an object.');
  return record;
}

/** A stored record as the golden file writes it: every Blob as its type and text. */
async function written(value: unknown): Promise<unknown> {
  if (value instanceof Blob) return { $blob: { type: value.type, text: await value.text() } };
  if (Array.isArray(value)) return Promise.all(value.map(written));
  if (!isJsonRecord(value)) return value;
  const entries = await Promise.all(
    Object.entries(value).map(async ([key, entry]) => [key, await written(entry)] as const),
  );
  return Object.fromEntries(entries);
}

/** The draft with each photo's bytes as text, so two drafts compare by what they mean. */
async function meaning(draft: StoredDraft | undefined): Promise<unknown> {
  return draft && written(draft);
}

async function rawStore<T>(
  mode: IDBTransactionMode,
  run: (store: IDBObjectStore) => IDBRequest<T>,
): Promise<T> {
  const opening = indexedDB.open('werkflow-drafts', 1);
  opening.onupgradeneeded = () => opening.result.createObjectStore('drafts', { keyPath: 'id' });
  const database = await new Promise<IDBDatabase>((resolve, reject) => {
    opening.onsuccess = () => resolve(opening.result);
    opening.onerror = () => reject(opening.error);
  });
  try {
    const request = run(database.transaction('drafts', mode).objectStore('drafts'));
    return await new Promise<T>((resolve, reject) => {
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  } finally {
    database.close();
  }
}

/** Stores a record exactly as given, as an earlier or later release left it on the phone. */
function storeRecord(record: unknown): Promise<IDBValidKey> {
  return rawStore('readwrite', (store) => store.put(record));
}

function storedRecords(): Promise<unknown[]> {
  return rawStore('readonly', (store) => store.getAll());
}

afterEach(async () => {
  await rawStore('readwrite', (store) => store.clear());
});

const versions = Object.entries(golden);
const latest = golden['1'];

describe('a stored draft of every version stays readable', () => {
  for (const [version, records] of versions)
    for (const [name, draft] of Object.entries(cases))
      test(`a "${name}" draft stored by version "${version}" reads as the same draft`, async () => {
        const record: unknown = Reflect.get(records, name);
        await storeRecord(revived(record));
        const read = (await listDraftsOnDevice(holder, NOW)).find((entry) => entry.id === draft.id);
        await pinned(async () => expect(await meaning(read)).toEqual(await meaning(draft)), NEVER_EDIT);
      });

  test('the writer of this version stores exactly the golden records of the latest version', async () => {
    for (const draft of Object.values(cases)) await changeDraftOnDevice(draft, draft.id, () => draft);
    const stored = await written(await storedRecords());
    const byId = Object.values(latest).toSorted((left, right) => left.id.localeCompare(right.id));
    await pinned(
      () => expect(stored).toEqual(byId),
      'The writer stores a record the golden file does not hold. ' + NEVER_EDIT,
    );
  });

  test('a field this version does not know is ignored, and the draft reads as before', async () => {
    await storeRecord({ ...revivedRecord(latest.text), laterField: { anything: true } });
    expect(await meaning((await listDraftsOnDevice(holder, NOW))[0])).toEqual(await meaning(cases.text));
  });
});

describe('a record this version cannot read stays on the device and shows to its person', () => {
  const storage = new Map<string, string>();
  Object.assign(globalThis, {
    localStorage: {
      getItem: (key: string) => storage.get(key) ?? null,
      setItem: (key: string, value: string) => void storage.set(key, value),
      removeItem: (key: string) => void storage.delete(key),
    },
  });
  const otherPerson: DraftHolder = { ...holder, userId: '9c000000-0000-4000-8000-000000000002' };
  // A lost-access draft past its seven days, of a later version: a sweep would delete it if it read it.
  const expiredAt = new Date(NOW.getTime() - DRAFT_NO_ACCESS_KEPT_MS).toISOString();
  const later = {
    ...revivedRecord(latest.noAccess),
    version: 2,
    refusal: { kind: 'no_access', at: expiredAt },
  };
  const broken = { ...revivedRecord(latest.text), title: 42 };

  test('a record of a later version is never listed, sent, changed or deleted by a sweep', async () => {
    await storeRecord(later);
    storage.set('werkflow:drafts-on-device', '1');
    expect(await listDraftsOnDevice(holder, NOW)).toEqual([]);
    await sweepExpiredDraftsOnDevice(NOW);
    let seen: StoredDraft | null | undefined;
    const answer = await changeDraftOnDevice(holder, cases.noAccess.id, (current) => {
      seen = current;
      return cases.noAccess;
    });
    expect(seen).toBeUndefined();
    expect(answer).toBeNull();
    expect(await written(await storedRecords())).toEqual([await written(later)]);
    for (let turn = 0; turn < 20; turn += 1) await new Promise((resolve) => setImmediate(resolve));
    expect(storage.get('werkflow:drafts-on-device')).toBe('1');
  });

  test('a record this version cannot parse shows as unreadable to its person only, and is never replaced', async () => {
    await storeRecord(broken);
    await storeRecord(later);
    await storeRecord(revived(latest.sealed));
    expect((await listDraftsOnDevice(holder, NOW)).map((entry) => entry.id)).toEqual([cases.sealed.id]);
    expect(await listUnreadableDraftsOnDevice(holder)).toEqual([
      { id: cases.text.id, jobId: cases.text.jobId },
      { id: cases.noAccess.id, jobId: cases.noAccess.jobId },
    ]);
    expect(await listUnreadableDraftsOnDevice(otherPerson)).toEqual([]);
    expect(await changeDraftOnDevice(holder, cases.text.id, () => null)).toBeNull();
    expect(await changeDraftOnDevice(holder, cases.text.id, () => cases.text)).toBeNull();
    expect(await listUnreadableDraftsOnDevice(holder)).toHaveLength(2);
  });

  test('the holder deletes an unreadable draft by its id, and nothing else goes', async () => {
    const otherOrganization: DraftHolder = {
      ...holder,
      organizationId: '9c000000-0000-4000-8000-0000000000a2',
    };
    await storeRecord(broken);
    await storeRecord(later);
    await storeRecord(revived(latest.sealed));
    storage.set('werkflow:drafts-on-device', '1');

    // Another person or organization removes nothing, also under the record's own id.
    expect(await deleteUnreadableDraftOnDevice(otherPerson, cases.text.id)).toBe(false);
    expect(await deleteUnreadableDraftOnDevice(otherOrganization, cases.text.id)).toBe(false);
    // A readable draft never goes this way: it has its own delete.
    expect(await deleteUnreadableDraftOnDevice(holder, cases.sealed.id)).toBe(false);
    expect(await storedRecords()).toHaveLength(3);

    expect(await deleteUnreadableDraftOnDevice(holder, cases.text.id)).toBe(true);
    expect(await listUnreadableDraftsOnDevice(holder)).toEqual([
      { id: cases.noAccess.id, jobId: cases.noAccess.jobId },
    ]);
    expect((await listDraftsOnDevice(holder, NOW)).map((entry) => entry.id)).toEqual([cases.sealed.id]);
    expect(storage.get('werkflow:drafts-on-device')).toBe('1');
  });

  test('deleting the last unreadable draft removes the device mark once a fresh count finds none', async () => {
    await storeRecord(later);
    storage.set('werkflow:drafts-on-device', '1');
    expect(await deleteUnreadableDraftOnDevice(holder, cases.noAccess.id)).toBe(true);
    for (let turn = 0; turn < 100 && storage.has('werkflow:drafts-on-device'); turn += 1)
      await new Promise((resolve) => setImmediate(resolve));
    expect(storage.has('werkflow:drafts-on-device')).toBe(false);
    expect(await storedRecords()).toEqual([]);
  });

  test('a record whose job this version cannot read still shows to its person, without a job', async () => {
    await storeRecord({ ...revivedRecord(latest.text), version: 2, jobId: { later: 'shape' } });
    expect(await listUnreadableDraftsOnDevice(holder)).toEqual([{ id: cases.text.id, jobId: null }]);
  });
});
